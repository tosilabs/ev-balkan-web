import assert from 'node:assert/strict';
import {assessOperating,connectorState,currentOperating,workingOnly,freshStatus,checkOperating} from '../dist/operating.mjs';
const now=Date.now(),generated=new Date(now).toISOString();
const station={finesId:'1',connections:[{label:'CCS2'}]};
const connector={plug_type:'CCS Combo 2 Plug (Cable Attached)',max_power_kw:150,status:'Available',available:true};
const assess=(connectors,extra={})=>assessOperating(station,{connectors},generated,{now,...extra});
assert.equal(assess([connector]).key,'working');
assert.equal(assess([{...connector,status:'Charging',available:false}]).available,0);
assert.equal(assess([{...connector,status:'Reserved',available:false}]).key,'working');
assert.equal(assess([{...connector,status:'Offline'}]).key,'offline');
assert.equal(connectorState({...connector,status:'Faulted'}).key,'offline');
assert.equal(assess([{...connector,status:'Unknown',available:false}]).key,'unknown');
assert.equal(assess([connector],{minPower:200}).key,'unknown');
assert.equal(assess([{...connector,plug_type:'Type 2'}]).key,'unknown');
assert.equal(assessOperating({...station,finesId:''},{connectors:[connector]},generated,{now}).key,'unknown');
assert.equal(assessOperating(station,{connectors:[connector]},new Date(now-600001).toISOString(),{now}).key,'unknown');
assert.equal(freshStatus(new Date(now+180000).toISOString(),now),false);
const good={...station,operating:assess([connector])};
assert.equal(currentOperating(good,now+600001).key,'unknown');
assert.equal(workingOnly([good,station,{...station,operating:assess([{...connector,status:'Faulted'}])}]).length,1);
const failed=await checkOperating([station],{request:async()=>{throw Error('offline');}});
assert.equal(failed[0].operating.key,'unknown');
console.log('Operational status: fresh evidence, occupied, offline, stale, connector and power matching passed');
